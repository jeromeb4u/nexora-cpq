export interface ApprovalRequestedInput {
  readonly to: string;
  readonly quoteNumber: string;
  readonly customerName: string;
  readonly requesterName: string;
  readonly requestedRate: number;
  readonly allowedRate: number;
  readonly mrr: Cents;
  readonly tcv: Cents;
  readonly justification: string;
  readonly url: string;
}

export function approvalRequested(input: ApprovalRequestedInput): EmailMessage {
  const subject = `Approval needed: ${input.quoteNumber} for ${input.customerName}`;
  const requested = formatRate(input.requestedRate);
  const allowed = formatRate(input.allowedRate);

  return {
    template: EmailTemplateId.APPROVAL_REQUESTED,
    to: input.to,
    subject,
    html: layout({
      preheader: `${input.requesterName} requested ${requested} on ${input.quoteNumber}.`,
      heading: `${input.quoteNumber} needs your approval`,
      paragraphs: [
        `${escapeHtml(input.requesterName)} has requested a <strong>${escapeHtml(requested)}</strong> discount for <strong>${escapeHtml(input.customerName)}</strong>, above their ${escapeHtml(allowed)} authority.`,
        `<em>“${escapeHtml(input.justification)}”</em>`,
      ],
      rows: [
        { label: 'Monthly recurring', value: formatMoney(input.mrr) },
        { label: 'Contract value', value: formatMoney(input.tcv) },
        { label: 'Discount requested', value: requested },
      ],
      action: { label: 'Review the request', url: input.url },
    }),
    text: textBody([
      `${input.quoteNumber} needs your approval`,
      '',
      `${input.requesterName} has requested a ${requested} discount for ${input.customerName}, above their ${allowed} authority.`,
      `Justification: ${input.justification}`,
      '',
      `Monthly recurring: ${formatMoney(input.mrr)}`,
      `Contract value: ${formatMoney(input.tcv)}`,
      '',
      `Review: ${input.url}`,
    ]),
  };
}

export interface ApprovalDecidedInput {
  readonly to: string;
  readonly quoteNumber: string;
  readonly customerName: string;
  readonly approverName: string;
  readonly rate: number;
  readonly note?: string | null;
  readonly url: string;
}

export function approvalGranted(input: ApprovalDecidedInput): EmailMessage {
  const rate = formatRate(input.rate);
  return {
    template: EmailTemplateId.APPROVAL_GRANTED,
    to: input.to,
    subject: `Approved: ${input.quoteNumber} for ${input.customerName}`,
    html: layout({
      preheader: `${input.approverName} approved your ${rate} discount.`,
      heading: `${input.quoteNumber} was approved`,
      paragraphs: [
        `${escapeHtml(input.approverName)} approved the <strong>${escapeHtml(rate)}</strong> discount for <strong>${escapeHtml(input.customerName)}</strong>. The quote can now be sent to the customer.`,
      ],
      action: { label: 'Open the quote', url: input.url },
    }),
    text: textBody([
      `${input.quoteNumber} was approved`,
      '',
      `${input.approverName} approved the ${rate} discount for ${input.customerName}. The quote can now be sent to the customer.`,
      '',
      `Open: ${input.url}`,
    ]),
  };
}

export function approvalRejected(input: ApprovalDecidedInput): EmailMessage {
  const rate = formatRate(input.rate);
  const note = input.note?.trim() || 'No reason was recorded.';
  return {
    template: EmailTemplateId.APPROVAL_REJECTED,
    to: input.to,
    subject: `Not approved: ${input.quoteNumber} for ${input.customerName}`,
    html: layout({
      preheader: `${input.approverName} did not approve the ${rate} discount.`,
      heading: `${input.quoteNumber} was not approved`,
      paragraphs: [
        `${escapeHtml(input.approverName)} did not approve the <strong>${escapeHtml(rate)}</strong> discount for <strong>${escapeHtml(input.customerName)}</strong>.`,
        `<em>“${escapeHtml(note)}”</em>`,
        'Revise the configuration or the discount, then request approval again.',
      ],
      action: { label: 'Revise the quote', url: input.url },
    }),
    text: textBody([
      `${input.quoteNumber} was not approved`,
      '',
      `${input.approverName} did not approve the ${rate} discount for ${input.customerName}.`,
      `Reason: ${note}`,
      '',
      `Revise: ${input.url}`,
    ]),
  };
}

export interface QuoteSentInput {
  readonly to: string;
  readonly contactName: string;
  readonly customerName: string;
  readonly quoteNumber: string;
  readonly mrr: Cents;
  readonly otc: Cents;
  readonly tcv: Cents;
  readonly contractMonths: number;
  readonly validUntil: Date | null;
  readonly representativeName: string;
  readonly documentUrl: string;
}

export function quoteSent(input: QuoteSentInput): EmailMessage {
  const validity = input.validUntil
    ? input.validUntil.toLocaleDateString('en-GB', {
        day: 'numeric',
        month: 'long',
        year: 'numeric',
      })
    : null;

  return {
    template: EmailTemplateId.QUOTE_SENT,
    to: input.to,
    subject: `Your Nexora quote ${input.quoteNumber}`,
    html: layout({
      preheader: `${formatMoney(input.mrr)} per month over ${input.contractMonths} months.`,
      heading: `Your quote ${input.quoteNumber}`,
      paragraphs: [
        `Dear ${escapeHtml(input.contactName)},`,
        `Thank you for considering Nexora Telecom. Please find the proposal for <strong>${escapeHtml(input.customerName)}</strong> summarised below; the full quote document is available at the link.`,
      ],
      rows: [
        { label: 'Monthly recurring', value: formatMoney(input.mrr) },
        { label: 'One-time charges', value: formatMoney(input.otc) },
        { label: 'Contract term', value: `${input.contractMonths} months` },
        { label: 'Total contract value', value: formatMoney(input.tcv) },
        ...(validity ? [{ label: 'Valid until', value: validity }] : []),
      ],
      action: { label: 'View the quote document', url: input.documentUrl },
      footnote: `Your account contact is ${escapeHtml(input.representativeName)}. Prices exclude VAT.`,
    }),
    text: textBody([
      `Dear ${input.contactName},`,
      '',
      `Thank you for considering Nexora Telecom. Your quote ${input.quoteNumber} for ${input.customerName}:`,
      '',
      `Monthly recurring: ${formatMoney(input.mrr)}`,
      `One-time charges: ${formatMoney(input.otc)}`,
      `Contract term: ${input.contractMonths} months`,
      `Total contract value: ${formatMoney(input.tcv)}`,
      validity ? `Valid until: ${validity}` : null,
      '',
      `Quote document: ${input.documentUrl}`,
      '',
      `Your account contact is ${input.representativeName}. Prices exclude VAT.`,
    ]),
  };
}
