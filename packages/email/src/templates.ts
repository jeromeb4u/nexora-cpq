import { type Cents, formatMoney, formatRate } from '@nexora/types';

import { type EmailMessage, EmailTemplateId } from './types';

/**
 * Email templates.
 *
 * Plain functions returning subject, HTML and text — no templating engine,
 * because four transactional messages do not justify one.
 *
 * Every interpolated value is escaped. Customer names, discount justifications
 * and rejection notes are all typed by users; rendering one unescaped would let
 * a rep put markup, or a convincing fake link, into an approver's inbox.
 */

const HTML_ESCAPES: Record<string, string> = {
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
  "'": '&#39;',
};

export function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, (character) => HTML_ESCAPES[character] ?? character);
}

/** Only absolute http(s) links are ever rendered; anything else is dropped. */
export function safeUrl(value: string): string | null {
  try {
    const url = new URL(value);
    return url.protocol === 'https:' || url.protocol === 'http:' ? url.toString() : null;
  } catch {
    return null;
  }
}

interface LayoutInput {
  readonly preheader: string;
  readonly heading: string;
  /** Pre-escaped HTML fragments. */
  readonly paragraphs: readonly string[];
  readonly rows?: readonly { readonly label: string; readonly value: string }[];
  readonly action?: { readonly label: string; readonly url: string };
  readonly footnote?: string;
}

/**
 * The shared shell: a single-column, table-based layout with inline styles,
 * because that is what email clients actually render consistently.
 */
function layout(input: LayoutInput): string {
  const url = input.action ? safeUrl(input.action.url) : null;

  const rows = input.rows?.length
    ? `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="margin:20px 0;border:1px solid #e3e7ee;border-radius:6px;border-collapse:separate">
        ${input.rows
          .map(
            (row, index) => `<tr>
              <td style="padding:10px 14px;font-size:13px;color:#4d5768;${index > 0 ? 'border-top:1px solid #e3e7ee;' : ''}">${escapeHtml(row.label)}</td>
              <td align="right" style="padding:10px 14px;font-size:13px;color:#171c24;font-weight:600;font-variant-numeric:tabular-nums;${index > 0 ? 'border-top:1px solid #e3e7ee;' : ''}">${escapeHtml(row.value)}</td>
            </tr>`,
          )
          .join('')}
      </table>`
    : '';

  const action =
    input.action && url
      ? `<table role="presentation" cellpadding="0" cellspacing="0" style="margin:24px 0"><tr><td style="border-radius:6px;background:#2449d6">
          <a href="${escapeHtml(url)}" style="display:inline-block;padding:10px 18px;font-size:14px;font-weight:600;color:#ffffff;text-decoration:none">${escapeHtml(input.action.label)}</a>
        </td></tr></table>`
      : '';

  return `<!doctype html>
<html lang="en">
  <body style="margin:0;padding:0;background:#f8f9fb;font-family:-apple-system,'Segoe UI',Roboto,Helvetica,Arial,sans-serif">
    <span style="display:none;max-height:0;overflow:hidden">${escapeHtml(input.preheader)}</span>
    <table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="background:#f8f9fb;padding:32px 16px">
      <tr><td align="center">
        <table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="max-width:560px;background:#ffffff;border:1px solid #e3e7ee;border-radius:8px">
          <tr><td style="padding:20px 28px;border-bottom:1px solid #e3e7ee">
            <span style="font-size:15px;font-weight:700;color:#171c24">Nexora</span>
            <span style="font-size:11px;letter-spacing:1px;text-transform:uppercase;color:#6b7689;margin-left:4px">Telecom</span>
          </td></tr>
          <tr><td style="padding:28px">
            <h1 style="margin:0 0 16px;font-size:18px;line-height:26px;color:#171c24">${escapeHtml(input.heading)}</h1>
            ${input.paragraphs.map((paragraph) => `<p style="margin:0 0 12px;font-size:14px;line-height:22px;color:#39414f">${paragraph}</p>`).join('')}
            ${rows}
            ${action}
            ${input.footnote ? `<p style="margin:16px 0 0;font-size:12px;line-height:18px;color:#6b7689">${input.footnote}</p>` : ''}
          </td></tr>
          <tr><td style="padding:16px 28px;border-top:1px solid #e3e7ee;font-size:11px;line-height:16px;color:#6b7689">
            Nexora Telecom is a fictional company. This message was generated by a portfolio demonstration system.
          </td></tr>
        </table>
      </td></tr>
    </table>
  </body>
</html>`;
}

/** Plain-text rendering of the same content. */
function textBody(lines: readonly (string | null | undefined)[]): string {
  return [
    ...lines.filter((line): line is string => typeof line === 'string'),
    '',
    '—',
    'Nexora Telecom is a fictional company. This message was generated by a portfolio demonstration system.',
  ].join('\n');
}

